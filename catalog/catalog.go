func Prefix(prefix string) []string {
	out := []string{}
	for k := range Terms {
		if len(k) >= len(prefix) && k[:len(prefix)] == prefix {
			out = append(out, k)
		}
	}
	sort.Strings(out)
	return out
}
func Search(text string) []string {
	out := []string{}
	for k, v := range Terms {
		if contains(k, text) || contains(v, text) {
			out = append(out, k)
		}
	}
	sort.Strings(out)
	return out
}
func contains(value, query string) bool {
	if query == "" {
		return true
	}
	for i := 0; i+len(query) <= len(value); i++ {
		if value[i:i+len(query)] == query {
			return true
		}
	}
	return false
}
